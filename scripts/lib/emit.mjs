/* ══ scripts/lib/emit.mjs — byte-stable generation of the site's data files ══
   A refresh that changes nothing should produce nothing. Before this, a run of
   scripts/build-crawl-data.mjs rewrote src/data/issueSignals.ts and
   src/data/crawlStats.ts on every invocation: the ordering read the wall clock,
   and the date stamp was taken inside the writer, so two runs over an identical
   crawl differed in the diff even when not one record moved.

   Two rules keep that from happening:

   1. selection and rendering are pure. No Date.now() inside a builder; the day
      arrives as an argument, so the same records render to the same bytes.
   2. a file is written only when its content changed, judged with the date
      masked out. Unchanged content leaves the file alone - same bytes, same
      mtime, and the date already in it stays put, which makes that stamp a
      content-updated date rather than a run-updated one.

   Ordering is defined here rather than at the call site so every artifact built
   from the crawl ties in the same direction.                            ═ */

import { existsSync, readFileSync, writeFileSync } from "node:fs";

/** Every ISO date reads as one token, so a date-only difference is not content. */
export function contentFingerprint(text) {
  return String(text).replace(/\d{4}-\d{2}-\d{2}/g, "DATE");
}

/**
 * Rows for the home-page wall, in a fixed order.
 *
 * The rank is beginner-labelled first, then the bigger catalog, then most
 * recently updated - the same signals the previous comparator used, read off
 * the stored timestamps instead of off `Date.now()`, so a re-run cannot reshuffle
 * near-equal rows. `repo` then `number` break the remaining ties, which is what
 * makes reordered input produce identical bytes.
 *
 * @param {any[]} issues rows from data/crawl/issues.jsonl
 * @param {{ limit?: number, perRepo?: number, helpful?: RegExp, asOf?: string, maxAgeDays?: number }} [options]
 * @returns {any[]}
 */
export function selectIssueSignals(issues, options = {}) {
  const {
    limit = 30, perRepo = 2,
    helpful = /good first issue|help wanted|beginner|easy|starter|difficulty easy/i,
    asOf, maxAgeDays = 45,
  } = options;
  const score = (i) => (helpful.test((i.labels ?? []).join(" ")) ? 1 : 0);
  /* the freshness window is measured from the run's own stamp, not from the
     machine clock, so the same crawl selects the same rows every time */
  const cut = asOf ? Date.parse(`${asOf}T00:00:00Z`) - maxAgeDays * 864e5 : null;

  const ranked = issues
    .filter((i) => i.state === "open" && !i.locked)
    .filter((i) => !(i.assignees ?? []).length)
    .filter((i) => i.updated_at && !Number.isNaN(Date.parse(i.updated_at)))
    .filter((i) => cut === null || Date.parse(i.updated_at) >= cut)
    .filter((i) => (i.repo_stars ?? 0) >= 2000)
    .filter((i) => (i.title ?? "").trim().length > 12)
    .map((i) => ({ ...i, helpful: score(i) }))
    .sort((a, b) =>
      b.helpful - a.helpful
      || (b.repo_stars ?? 0) - (a.repo_stars ?? 0)
      || String(b.updated_at).localeCompare(String(a.updated_at))
      || String(a.repo).localeCompare(String(b.repo))
      || (a.number ?? 0) - (b.number ?? 0));

  const perRepoSeen = new Map();
  const picked = [];
  for (const i of ranked) {
    const n = perRepoSeen.get(i.repo) ?? 0;
    if (n >= perRepo) continue;
    perRepoSeen.set(i.repo, n + 1);
    picked.push(i);
    if (picked.length === limit) break;
  }

  return picked.map((i) => ({
    repo: i.repo,
    title: String(i.title).trim().replace(/\s+/g, " ").slice(0, 120),
    url: i.url,
    number: i.number,
    stars: i.repo_stars,
    lang: i.repo_language ?? null,
    labels: (i.labels ?? []).slice(0, 3),
    updated: String(i.updated_at).slice(0, 10),
    beginner: !!i.helpful,
  }));
}

const TYPE_DECL = `export interface IssueSignal {
  repo: string; title: string; url: string; number: number;
  stars: number; lang: string | null; labels: string[];
  updated: string; beginner: boolean;
}`;

/**
 * @param {any[]} rows as returned by selectIssueSignals
 * @param {string} asOf YYYY-MM-DD stamp for the "fresh since" caption
 * @returns {string} the whole file, ending in one newline
 */
export function renderIssueSignals(rows, asOf) {
  return `/* GENERATED by scripts/build-crawl-data.mjs from data/crawl/issues.jsonl.
   ${rows.length} real open issues, crawled ${asOf}.
   Do not edit by hand - rerun the script. */
${TYPE_DECL}

export const ISSUE_SIGNALS: IssueSignal[] = ${JSON.stringify(rows, null, 2)} as const;

/** when the sample was crawled, for the "fresh since" caption */
export const ISSUE_SIGNALS_AS_OF = "${asOf}";
`;
}

/**
 * @typedef {object} CrawlCounts
 * @property {number} issues
 * @property {number} reposWithIssues
 * @property {number} catalogRepos
 * @property {number} orgs
 * @property {number} languages
 * @property {number} beginnerLabelled
 * @property {string} mostRecentUpdate an ISO timestamp from a crawl row
 */

/**
 * @param {CrawlCounts} counts
 * @param {string} asOf YYYY-MM-DD
 * @returns {string}
 */
export function renderCrawlStats(counts, asOf) {
  const c = counts;
  return `/* GENERATED by scripts/build-crawl-data.mjs. Counts of rows in data/crawl/,
   so anything the site states from here is literally true of the snapshot.
   Do not edit by hand - rerun the script. */
export const CRAWL = {
  issues: ${c.issues},
  reposWithIssues: ${c.reposWithIssues},
  catalogRepos: ${c.catalogRepos},
  orgs: ${c.orgs},
  languages: ${c.languages},
  beginnerLabelled: ${c.beginnerLabelled},
  mostRecentUpdate: "${String(c.mostRecentUpdate).slice(0, 10)}",
  crawledAt: "${asOf}",
} as const;
`;
}

/**
 * Write only when the bytes changed. Dates are masked before the comparison, so
 * an artifact whose records all match the one on disk is left untouched and
 * keeps the stamp it already carried.
 *
 * @param {string} file absolute path
 * @param {string} text the rendered artifact
 * @param {{ read?: (p: string) => string | null, write?: (p: string, t: string) => void }} [io]
 * @returns {{ written: boolean, asOf: string | null }} asOf is the stamp on disk
 *   afterwards - the new one when it was written, the retained one when it was not
 */
export function emitArtifact(file, text, io = {}) {
  const read = io.read ?? ((p) => (existsSync(p) ? readFileSync(p, "utf8") : null));
  const write = io.write ?? ((p, t) => writeFileSync(p, t));
  const previous = read(file);
  if (previous !== null && contentFingerprint(previous) === contentFingerprint(text)) {
    return { written: false, asOf: stampOf(previous) };
  }
  write(file, text);
  return { written: true, asOf: stampOf(text) };
}

/** the date an artifact carries, whichever line holds it */
export function stampOf(text) {
  return /(\d{4}-\d{2}-\d{2})/.exec(String(text))?.[1] ?? null;
}
